// unchanged fails t when file's contents or modification time changed.
func unchanged(t *testing.T, file string, body string, mod time.Time) {
	t.Helper()
	fi, err := os.Lstat(file)
	if err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(file); string(b) != body || !fi.ModTime().Equal(mod) {
		t.Errorf("%s changed: %q at %v", file, b, fi.ModTime())
	}
}

func TestLockLeavesAnotherProgramsFileAlone(t *testing.T) {
	for name, body := range map[string]string{
		"a Cargo.lock":      "# This file is automatically @generated by Cargo.\nversion = 3\n",
		"binary garbage":    "not a pid\x00\xff",
		"a minus pid":       "-1\n",
		"three lines":       "1\nhost\nmore\n",
		"a pid too long":    strings.Repeat("1", 11) + "\nhost\n",
		"a host too long":   "1\n" + strings.Repeat("h", 256) + "\n",
		"an oversized file": strings.Repeat("x", 4096),
		"NULs, then text":   "\x00\x00text",
		"NULs past a limit": strings.Repeat("\x00", maxHolder+1),
		"a NUL inside":      "12\x003\nhost\n",
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			lockFile := filepath.Join(dir, "Cargo.lock")
			if err := os.WriteFile(lockFile, []byte(body), 0o644); err != nil {
				t.Fatal(err)
			}
			old := time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)
			if err := os.Chtimes(lockFile, old, old); err != nil {
				t.Fatal(err)
			}
			_, err := Lock(context.Background(), filepath.Join(dir, "Cargo"), 0) // --state ~/proj/Cargo
			if err == nil || !strings.Contains(err.Error(), lockFile) || !strings.Contains(err.Error(), "not sitboard's") {
				t.Fatalf("err %v", err)
			}
			unchanged(t, lockFile, body, old)
		})
	}
}

func TestLockRefusesALinkAndWhatIsNotAFile(t *testing.T) {
	t.Run("a link to a file", func(t *testing.T) {
		dir := t.TempDir()
		victim := filepath.Join(dir, "victim.txt")
		if err := os.WriteFile(victim, []byte("important"), 0o644); err != nil {
			t.Fatal(err)
		}
		fi, _ := os.Stat(victim)
		if err := os.Symlink(victim, filepath.Join(dir, "state.json.lock")); err != nil {
			t.Fatal(err)
		}
		_, err := Lock(context.Background(), filepath.Join(dir, "state.json"), 0)
		if err == nil || !strings.Contains(err.Error(), "is a link") {
			t.Fatalf("err %v", err)
		}
		unchanged(t, victim, "important", fi.ModTime())
	})
	t.Run("a link to nothing", func(t *testing.T) {
		dir := t.TempDir()
		target := filepath.Join(dir, "would-be-created")
		if err := os.Symlink(target, filepath.Join(dir, "state.json.lock")); err != nil {
			t.Fatal(err)
		}
		_, err := Lock(context.Background(), filepath.Join(dir, "state.json"), 0)
		if err == nil || !strings.Contains(err.Error(), "is a link") {
			t.Fatalf("err %v", err)
		}
		if _, err := os.Lstat(target); !errors.Is(err, os.ErrNotExist) {
			t.Errorf("the link's target was created: %v", err)
		}
	})
	t.Run("a named pipe", func(t *testing.T) {
		dir := t.TempDir()
		if err := syscall.Mkfifo(filepath.Join(dir, "state.json.lock"), 0o600); err != nil {
			t.Fatal(err)
		}
		done := make(chan error, 1)
		go func() { _, err := Lock(context.Background(), filepath.Join(dir, "state.json"), 0); done <- err }()
		select {
		case err := <-done:
			if err == nil || !strings.Contains(err.Error(), "not a regular file") {
				t.Fatalf("err %v", err)
			}
		case <-time.After(10 * time.Second):
			t.Fatal("Lock hangs on a named pipe")
		}
	})
	t.Run("a folder", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.Mkdir(filepath.Join(dir, "state.json.lock"), 0o700); err != nil {
			t.Fatal(err)
		}
		if _, err := Lock(context.Background(), filepath.Join(dir, "state.json"), 0); err == nil {
			t.Fatal("locked a folder")
		}
	})
}

func TestLockFileThatCannotBeWritten(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root opens any file")
	}
	t.Run("read-only: locked without writing", func(t *testing.T) {
		file := filepath.Join(t.TempDir(), "state.json")
		body := "4242\nOld-Name.local\n" // left by a run of another user, say
		if err := os.WriteFile(LockFile(file), []byte(body), 0o400); err != nil {
			t.Fatal(err)
		}
		fi, _ := os.Stat(LockFile(file))
		l := lockOrFail(t, file, 0)
		if _, err := Lock(context.Background(), file, 0); !errors.As(err, new(*LockedError)) {
			t.Errorf("a read-only lock does not hold: %v", err)
		}
		if err := l.Release(); err != nil {
			t.Fatal(err)
		}
		unchanged(t, LockFile(file), body, fi.ModTime())
	})
	t.Run("no access: says what to do", func(t *testing.T) {
		file := filepath.Join(t.TempDir(), "state.json")
		if err := os.WriteFile(LockFile(file), nil, 0o000); err != nil {
			t.Fatal(err)
		}
		_, err := Lock(context.Background(), file, 0)
		if err == nil || !strings.Contains(err.Error(), "cannot open the lock file") || !strings.Contains(err.Error(), "remove it") {
			t.Fatalf("err %v", err)
		}
		if errors.As(err, new(*LockedError)) {
			t.Error("reported as held although nobody holds it")
		}
	})
}

func TestLockWaitEndsWithTheContext(t *testing.T) {
	file := filepath.Join(t.TempDir(), "state.json")
	lockOrFail(t, file, 0) // never let go during the test
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan error, 1)
	go func() { _, err := Lock(ctx, file, time.Hour); done <- err }()
	time.Sleep(100 * time.Millisecond)
	cancel()
	select {
	case err := <-done:
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("err %v", err)
		}
	case <-time.After(10 * time.Second):
		t.Fatal("the wait went on after the context ended")
	}
	if _, err := Lock(ctx, filepath.Join(t.TempDir(), "free.json"), 0); !errors.Is(err, context.Canceled) {
		t.Errorf("an ended context still took a free lock: %v", err)
	}
}

// spawnAndExit (a helper process) takes the lock on file, starts a long-lived
// child in its own process group, writes the child's pid to pidFile and exits
// without letting go: only the child could still hold the lock.
func spawnAndExit(file, pidFile string) {
	l, err := Lock(context.Background(), file, 0)
	if err != nil {
		os.Exit(3)
	}
	helperLock = l
	child := exec.Command("sleep", "60")
	child.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	if err := child.Start(); err != nil {
		os.Exit(4)
	}
	if err := os.WriteFile(pidFile, []byte(strconv.Itoa(child.Process.Pid)), 0o600); err != nil {
		os.Exit(5)
	}
	os.Exit(0)
}

func TestAChildProcessHoldsNoLock(t *testing.T) {
	file := filepath.Join(t.TempDir(), "state.json")
	pidFile := filepath.Join(t.TempDir(), "child.pid")
	helper := exec.Command(os.Args[0], "-test.run=^$")
	helper.Env = append(os.Environ(), "SITBOARD_LOCK_SPAWN="+file, "SITBOARD_LOCK_CHILD="+pidFile)
	if out, err := helper.CombinedOutput(); err != nil {
		t.Fatalf("helper: %v %s", err, out)
	}
	b, err := os.ReadFile(pidFile)
	if err != nil {
		t.Fatal(err)
	}
	pid, err := strconv.Atoi(string(b))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = syscall.Kill(pid, syscall.SIGKILL) })
	if err := syscall.Kill(pid, 0); err != nil {
		t.Fatalf("the child is not running: %v", err)
	}
	// The helper is gone and its child lives on: the lock is free at once.
	lockOrFail(t, file, 0)
	// And the child has no descriptor of the lock file.
	switch runtime.GOOS {
	case "linux":
		fds, err := os.ReadDir("/proc/" + strconv.Itoa(pid) + "/fd")
		if err != nil {
			t.Fatal(err)
		}
		for _, fd := range fds {
			if l, _ := os.Readlink("/proc/" + strconv.Itoa(pid) + "/fd/" + fd.Name()); strings.HasSuffix(l, ".lock") {
				t.Errorf("the child holds %s", l)
			}
		}
	default:
		lsof, err := exec.LookPath("lsof")
		if err != nil {
			t.Skip("no lsof to list the child's files")
		}
		out, _ := exec.Command(lsof, "-a", "-p", strconv.Itoa(pid), "-Fn").Output() // exit 1 when it lists nothing
		if strings.Contains(string(out), ".lock") {
			t.Errorf("the child holds the lock file:\n%s", out)
		}
		if !strings.Contains(string(out), "\n") {
			t.Logf("lsof listed nothing for the child")
		}
	}
}

func TestLockDoesNotBlockOnANamedPipeItCannotWrite(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root opens any file for writing")
	}
	dir := t.TempDir()
	if err := syscall.Mkfifo(filepath.Join(dir, "state.json.lock"), 0o400); err != nil {
		t.Fatal(err)
	}
	done := make(chan error, 1)
	go func() { _, err := Lock(context.Background(), filepath.Join(dir, "state.json"), 0); done <- err }()
	select {
	case err := <-done:
		if err == nil || !strings.Contains(err.Error(), "not a regular file") {
			t.Fatalf("err %v", err)
		}
	case <-time.After(10 * time.Second):
		// Unblock the open so the goroutine ends.
		if w, err := os.OpenFile(filepath.Join(dir, "state.json.lock"), os.O_WRONLY|syscall.O_NONBLOCK, 0); err == nil {
			_ = w.Close()
		}
		t.Fatal("Lock hangs opening a named pipe read-only")
	}
}

// Another program's file is told apart before locking too: one that its
// program holds locked is not reported as another sitboard.
func TestAnotherProgramsHeldFileIsNotCalledASitboard(t *testing.T) {
	dir := t.TempDir()
	lockFile := filepath.Join(dir, "Cargo.lock")
	if err := os.WriteFile(lockFile, []byte("version = 3\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	f, err := os.Open(lockFile)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		t.Fatal(err)
	}
	_, err = Lock(context.Background(), filepath.Join(dir, "Cargo"), 0)
	if errors.As(err, new(*LockedError)) || err == nil || !strings.Contains(err.Error(), "not sitboard's") {
		t.Fatalf("err %v", err)
	}
}

// What appears in the lock file while it is being locked is checked again
// before anything is written over it.
func TestLockChecksTheFileAgainOnceLocked(t *testing.T) {
	file := filepath.Join(t.TempDir(), "state.json")
	body := "written by another program meanwhile\n"
	old := flock
	flock = func(fd int, how int) error {
		if err := os.WriteFile(LockFile(file), []byte(body), 0o600); err != nil {
			t.Error(err)
		}
		return old(fd, how)
	}
	t.Cleanup(func() { flock = old })
	_, err := Lock(context.Background(), file, 0)
	if err == nil || !strings.Contains(err.Error(), "not sitboard's") {
		t.Fatalf("err %v", err)
	}
	if b, _ := os.ReadFile(LockFile(file)); string(b) != body {
		t.Errorf("written over: %q", b)
	}
}

// A lock file swapped for a link (to the very file it was) between open and
// lock is not taken: the name must still be that file itself.
func TestLockRefusesANameSwappedForALink(t *testing.T) {
	dir := t.TempDir()
	file := filepath.Join(dir, "state.json")
	moved := filepath.Join(dir, "elsewhere")
	old := flock
	calls := 0
	flock = func(fd int, how int) error {
		calls++
		if calls == 1 {
			if err := os.Rename(LockFile(file), moved); err != nil {
				t.Error(err)
			}
			if err := os.Symlink(moved, LockFile(file)); err != nil {
				t.Error(err)
			}
		}
		return old(fd, how)
	}
	t.Cleanup(func() { flock = old })
	_, err := Lock(context.Background(), file, 0)
	if err == nil || !strings.Contains(err.Error(), "is a link") {
		t.Fatalf("err %v", err)
	}
	if b, _ := os.ReadFile(moved); len(b) != 0 {
		t.Errorf("wrote into the link's target: %q", b)
	}
}
