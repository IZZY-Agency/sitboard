var paths = []struct{ name, path string }{
	{"snapshot", PathSnapshot},
	{"events", PathEvents},
	{"catchup", PathCatchup},
	{"leftovers", PathLeftovers},
	{"jump", PathJump},
	{"seen", PathSeen},
	{"catchupRead", PathCatchupRead},
	{"forgetGrouping", PathForgetGrouping},
}

// TypeScript returns the content of web/src/contract.gen.ts. It panics when a
// contract type uses a Go type it cannot map, so a missed case fails the tests.
func TypeScript() string {
	enums := map[reflect.Type]string{}
	for _, e := range enumList() {
		enums[e.typ] = e.name
	}
	structs := map[reflect.Type]bool{}
	for _, s := range structList() {
		structs[s] = true
	}

	var b strings.Builder
	b.WriteString("// Code generated by `go run ./internal/contract/gen`. DO NOT EDIT.\n")
	b.WriteString("// Source of truth: internal/contract/contract.go. Regenerate with `make contract`.\n\n")
	fmt.Fprintf(&b, "export const CONTRACT_VERSION = %d;\n\n", Version)

	b.WriteString("export const Paths = {\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "  %s: %s,\n", p.name, strconv.Quote(p.path))
	}
	b.WriteString("} as const;\n\n")
	fmt.Fprintf(&b, "export const EVENT_SNAPSHOT = %s;\n\n", strconv.Quote(EventSnapshot))
	b.WriteString("/** The only form of Artifact.url; the page links nothing else. */\n")
	fmt.Fprintf(&b, "export const ARTIFACT_URL_PATTERN = new RegExp(%s);\n\n", strconv.Quote(ArtifactURLPattern))

	b.WriteString("/** RFC 3339 time, UTC. */\nexport type Timestamp = string;\n")

	for _, e := range enumList() {
		quoted := make([]string, len(e.values))
		for i, v := range e.values {
			quoted[i] = strconv.Quote(v)
		}
		fmt.Fprintf(&b, "\nexport type %s = %s;\n", e.name, strings.Join(quoted, " | "))
		fmt.Fprintf(&b, "export const %sValues: readonly %s[] = [%s];\n", e.name, e.name, strings.Join(quoted, ", "))
	}

	for _, s := range structList() {
		fmt.Fprintf(&b, "\nexport interface %s {\n", s.Name())
		for f := range s.Fields() {
			name, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
			if name == "" || name == "-" {
				panic(fmt.Sprintf("contract: %s.%s needs a json name", s.Name(), f.Name))
			}
			optional := strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero")
			typ := tsType(f.Type, enums, structs)
			if f.Type.Kind() == reflect.Pointer && !optional {
				typ += " | null"
			}
			q := ""
			if optional {
				q = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", name, q, typ)
		}
		b.WriteString("}\n")
	}
	return b.String()
}

var timeType = reflect.TypeFor[time.Time]()

func tsType(t reflect.Type, enums map[reflect.Type]string, structs map[reflect.Type]bool) string {
	if t == timeType {
		return "Timestamp"
	}
	if name, ok := enums[t]; ok {
		return name
	}
	switch t.Kind() {
	case reflect.String:
		if t.Name() != "string" {
			panic(fmt.Sprintf("contract: string type %s is not in enumList", t.Name()))
		}
		return "string"
	case reflect.Int, reflect.Int64, reflect.Uint64, reflect.Float64:
		return "number"
	case reflect.Bool:
		return "boolean"
	case reflect.Slice:
		return tsType(t.Elem(), enums, structs) + "[]"
	case reflect.Pointer:
		return tsType(t.Elem(), enums, structs)
	case reflect.Struct:
		if !structs[t] {
			panic(fmt.Sprintf("contract: struct %s is not in structList", t.Name()))
		}
		return t.Name()
	}
	panic(fmt.Sprintf("contract: no TypeScript mapping for %s", t))
}
